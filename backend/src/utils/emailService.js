// ======================================================
// GENERIC SEND FUNCTION
// ======================================================
async function sendEmail(to, subject, html) {
  try {
    await transporter.sendMail({
      from: `"Eftech HR" <${process.env.EMAIL_USER}>`,
      to,
      subject,
      html
    });

    console.log("📧 Email sent to", to);
  } catch (err) {
    console.error("❌ Email failed:", err);
  }
}

