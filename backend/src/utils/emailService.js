// ======================================================
// HELPER: FORMAT TARIKH DD/MM/YYYY
// ======================================================
function formatDate(dateString) {
  const date = new Date(dateString);
  return date.toLocaleDateString("en-GB"); // dd/mm/yyyy format
}

// ======================================================
// HELPER: FULL LEAVE TYPE NAME
// ======================================================
const leaveTypeFullName = {
  AL: "Annual / Emergency Leave",
  MC: "Medical Leave",
  HOSP: "Hospitalization Leave",
  PAT: "Paternity Leave",
  MAT: "Maternity Leave",
  COMP_A: "Compassionate Leave A",
  COMP_B: "Compassionate Leave B",
  MAR: "Marriage Leave",
  UNPAID: "Unpaid Leave"
};

function getFullLeaveType(code) {
  return leaveTypeFullName[code] || code;
}

